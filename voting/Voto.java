package voting;

public class Voto {
    int idCandidato;

    public Voto() {
    }

    public Voto(int idCandidato) {
        this.idCandidato = idCandidato;
    }

    public int getIdCandidato() {
        return idCandidato;
    }

    public void setIdCandidato(int idCandidato) {
        this.idCandidato = idCandidato;
    }
}